"""Generate plugin/src/AtlasData.h from the trained atlas.

The plugin mocks the *sound* but not the *map*: the coordinates, the scale and
the mutual-kNN graph here are the real ones the model was trained against, so
the geometry a user navigates is authentic from day one. Only the timbre at
each anchor is fake (see MockVoice).

    python plugin/tools/export_atlas.py                  # uses local-model/
    python plugin/tools/export_atlas.py --atlas path.npz
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "src" / "midibrave" / "atlas_flow_manifest.py"


def split_presets(ids: list[str]) -> list[str]:
    """Which presets the model never saw, as atlas_flow_manifest.split_presets does it.

    Reproduced rather than imported: that module pulls in soundfile, which this
    script does not otherwise need. It is the same hash-ordered split, and the
    seed is read out of it so the two cannot drift apart silently -- the three
    rings the map draws would otherwise end up around the wrong presets, which
    is the kind of wrong that looks right.
    """
    found = re.search(r"^SEED\s*=\s*(\d+)", MANIFEST.read_text(encoding="utf-8"), re.M)
    if not found:
        raise SystemExit(f"no SEED in {MANIFEST}")
    seed = int(found.group(1))
    ordered = sorted(ids, key=lambda item: hashlib.sha256(f"{seed}:{item}".encode()).digest())
    role = {item: "validation" for item in ordered[:2]}
    role.update({item: "test" for item in ordered[2:5]})
    return [role.get(item, "train") for item in ids]


def emit(atlas: Path, out: Path) -> None:
    d = np.load(atlas)
    coords = np.asarray(d["coordinates"], dtype=np.float32)   # [50, 8]
    scale = np.asarray(d["scale"], dtype=np.float32)          # [8]
    knn = np.asarray(d["mutual_knn"])                         # [50, 50]
    anchors = np.asarray(d["anchors"], dtype=np.float32)      # [50, 128]
    ids = [str(x) for x in d["preset_ids"]]
    split = split_presets(ids)
    n, dim = coords.shape

    lines: list[str] = []
    w = lines.append
    w("// Generated by plugin/tools/export_atlas.py -- do not edit by hand.")
    w(f"// Source: {atlas.name}  ({n} presets, {dim}-D atlas)")
    w("#pragma once")
    w("")
    w("namespace atlasflow {")
    w("")
    w(f"inline constexpr int kPresetCount = {n};")
    w(f"inline constexpr int kAtlasDims  = {dim};")
    w("")
    w("// Per-preset coordinates in the 8-D PCA atlas, row-major [preset][dim].")
    w("inline constexpr float kCoordinates[kPresetCount][kAtlasDims] = {")
    for row in coords:
        w("    {" + ", ".join(f"{v:.6f}f" for v in row) + "},")
    w("};")
    w("")
    w("// Per-dimension scale; distances are measured in these units, not raw.")
    w("inline constexpr float kScale[kAtlasDims] = {")
    w("    " + ", ".join(f"{v:.6f}f" for v in scale))
    w("};")
    w("")
    w("// Mutual k-nearest-neighbour adjacency. Edges are what the map draws and")
    w("// what a morph routes along.")
    w("inline constexpr bool kNeighbours[kPresetCount][kPresetCount] = {")
    for row in knn:
        w("    {" + ", ".join("true " if bool(v) else "false" for v in row) + "},")
    w("};")
    w("")
    w("// Per-preset 128-D anchor: the canonical timbre the flow predicts around.")
    w("// A plan interpolates these along the route it takes across the graph.")
    w(f"inline constexpr int kAnchorDims = {anchors.shape[1]};")
    w("inline constexpr float kAnchors[kPresetCount][kAnchorDims] = {")
    for row in anchors:
        w("    {" + ", ".join(f"{v:.7g}f" for v in row) + "},")
    w("};")
    w("")
    w("inline constexpr const char* kPresetIds[kPresetCount] = {")
    for pid in ids:
        w(f'    "{pid}",')
    w("};")
    w("")
    w("// Which presets the model was trained on. The map rings the held-out ones:")
    w("// what you hear there is entirely generated, and that is worth seeing.")
    w("enum PresetSplit { kTrain = 0, kValidation = 1, kTest = 2 };")
    w("inline constexpr unsigned char kSplit[kPresetCount] = {")
    names = {"train": "kTrain", "validation": "kValidation", "test": "kTest"}
    w("    " + ", ".join(names[role] for role in split))
    w("};")
    w("")
    w("}  // namespace atlasflow")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    edges = int(np.triu(knn, 1).sum())
    print(f"wrote {out.relative_to(ROOT)}")
    print(f"  {n} presets, {dim}-D, {edges} undirected edges, {out.stat().st_size/1024:.0f} KiB")
    print(f"  held out: {split.count('validation')} validation, {split.count('test')} test")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--atlas", type=Path, default=ROOT / "local-model" / "pad-top50-atlas.npz")
    p.add_argument("--out", type=Path, default=ROOT / "plugin" / "src" / "AtlasData.h")
    a = p.parse_args()
    if not a.atlas.exists():
        raise SystemExit(
            f"atlas not found: {a.atlas}\n"
            "Fetch it with:  bash scripts/atlas_flow/fetch_local_model.sh"
        )
    a.out.parent.mkdir(parents=True, exist_ok=True)
    emit(a.atlas, a.out)


if __name__ == "__main__":
    main()
